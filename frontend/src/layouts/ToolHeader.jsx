function resolveTitle(pathname) {
  if (PAGE_TITLES[pathname]) return { title: PAGE_TITLES[pathname], icon: ICONS[pathname] };
  for (const [route, title] of Object.entries(PAGE_TITLES)) {
    if (pathname.startsWith(route + '/')) return { title, icon: ICONS[route] };
  }
  return { title: '', icon: null };
}

